const assert = require('node:assert/strict')
const { readFile } = require('node:fs/promises')
const path = require('node:path')
const test = require('node:test')

const root = path.resolve(__dirname, '..')

async function source(relative) {
  return readFile(path.join(root, relative), 'utf8')
}

test('all third-party GitHub Actions are pinned to immutable commits', async () => {
  for (const file of ['release.yml', 'publish-production-components.yml', 'verify-component-signing-secret.yml', 'android-mobile-release.yml', 'apple-virtual-tests.yml', 'ci.yml', 'upstream-watch.yml']) {
    const workflow = await source(path.join('.github', 'workflows', file))
    const uses = [...workflow.matchAll(/uses:\s+([^\s#]+)@([^\s#]+)/g)]
    assert.ok(uses.length > 0, `${file} must use at least one pinned action`)
    for (const match of uses) assert.match(match[2], /^[0-9a-f]{40}$/, `${file}: ${match[0]}`)
  }
})

test('signed Android publication follows the tag and waits for the verified desktop release', async () => {
  const workflow = await source(path.join('.github', 'workflows', 'android-mobile-release.yml'))
  assert.match(workflow, /push:[\s\S]*tags:[\s\S]*'v\*'/u)
  assert.ok(workflow.includes('RELEASE_TAG: ${{ inputs.tag || github.ref_name }}'))
  assert.match(workflow, /Waiting for verified desktop release/u)
  assert.match(workflow, /gh release upload "\$RELEASE_TAG"/u)
  assert.match(workflow, /seq 1 180/u)
  assert.match(workflow, /android-universal\.apk\.sha256/u)
  assert.match(workflow, /Preserving the existing immutable APK/u)
  assert.match(workflow, /Verify public signed APK bytes and identity/u)
  assert.doesNotMatch(workflow, /--clobber|assembleDebug|app-debug\.apk/u)
  const desktopWorkflow = await source(path.join('.github', 'workflows', 'release.yml'))
  assert.match(desktopWorkflow, /overwrite_files: false/u)
  assert.match(desktopWorkflow, /draft: true/u)
  assert.match(desktopWorkflow, /push:[\s\S]*tags:[\s\S]*'v\*'/u)
  assert.doesNotMatch(desktopWorkflow, /release-retry\/v/u)
  assert.match(desktopWorkflow, /ref: \$\{\{ env\.RELEASE_TAG \}\}/u)
  assert.match(desktopWorkflow, /--allow-downgrade --force/u)
  assert.match(desktopWorkflow, /tag_name: \$\{\{ env\.RELEASE_TAG \}\}/u)
  assert.match(desktopWorkflow, /Refuse an existing release mutation/u)
  assert.match(desktopWorkflow, /uploads\.github\.com\/repos\/\$GITHUB_REPOSITORY\/releases\/\$release_id\/assets/u)
  assert.match(desktopWorkflow, /--method PATCH "repos\/\$GITHUB_REPOSITORY\/releases\/\$snapshot_id" -F draft=false/u)
  assert.doesNotMatch(desktopWorkflow, /^\s*gh release (?:upload|edit|view)/mu)
  assert.match(desktopWorkflow, /Verify draft assets and publish atomically/u)
  assert.match(desktopWorkflow, /sha256sum -c SHA256SUMS\.txt/u)
  assert.match(workflow, /--json isDraft/u)
})

test('macOS release artifacts are explicitly unsigned with a one-click installer helper', async () => {
  const pkg = JSON.parse(await source('package.json'))
  const builder = await source('scripts/build-release.mjs')
  const workflow = await source(path.join('.github', 'workflows', 'release.yml'))
  assert.equal(pkg.scripts['dist:mac'], 'node scripts/build-release.mjs')
  assert.equal(pkg.build.mac.identity, null)
  assert.notEqual(pkg.build.mac.hardenedRuntime, true)
  assert.notEqual(pkg.build.mac.notarize, true)
  assert.equal(pkg.build.afterAllArtifactBuild, 'scripts/afterAllArtifactBuild.cjs')
  for (const contract of ['CSC_LINK', 'CSC_KEY_PASSWORD', 'APPLE_API_KEY', 'APPLE_API_KEY_ID', 'APPLE_API_ISSUER', 'APPLE_TEAM_ID', "CSC_IDENTITY_AUTO_DISCOVERY === 'true'", 'macOS unsigned packaging refuses Developer ID / notarization environment']) assert.ok(builder.includes(contract), contract)
  assert.match(workflow, /Build unsigned macOS packages/u)
  assert.match(workflow, /CSC_IDENTITY_AUTO_DISCOVERY: 'false'/u)
  assert.match(workflow, /Verify unsigned macOS packages/u)
  for (const forbidden of ['macos-signing', 'xcrun notarytool submit', 'xcrun stapler', 'codesign --verify', 'spctl --assess', 'secrets.APPLE_NOTARY', 'secrets.MACOS_DEVELOPER_ID']) assert.ok(!workflow.includes(forbidden), forbidden)
  const matrixPrefix = workflow.slice(0, workflow.indexOf('steps:'))
  assert.doesNotMatch(matrixPrefix, /MACOS_DEVELOPER_ID|APPLE_NOTARY/u)
})

